func generate(t *testing.T, cfg Config) string {
	t.Helper()
	src, err := Generate([]byte(fixture), cfg, "ocsf")
	if err != nil {
		t.Fatal(err)
	}
	return string(src)
}

func TestGenerate(t *testing.T) {
	src := generate(t, Config{Classes: []string{"thing_seen"}, Objects: []string{"network_endpoint"}})
	for _, want := range []string{
		"// Code generated by cmd/ocsfgen from OCSF 9.9.9; DO NOT EDIT.",
		`const SchemaVersion = "9.9.9"`,
		"ThingSeenClassUID    = 9001",
		"ThingSeenCategoryUID = 9",
		"// Constraint at_least_one: peer, note.",
		"Not generated (object not in gen.yaml): device (device).",
		"A thing was seen.",
		"ActivityID int `json:\"activity_id\"`", // required scalar: no omitempty
		"Time       int64 `json:\"time\"`",      // timestamp_t
		"Peer       *NetworkEndpoint `json:\"peer,omitempty\"`",
		"Peers      []NetworkEndpoint `json:\"peers,omitempty\"`",
		"Unmapped   map[string]any `json:\"unmapped,omitempty\"`",
		"Tags       []string `json:\"tags,omitempty\"`",
		"ThingSeenActivityIDSeenIt  = 1  // Seen It",
		"ThingSeenTypeUIDSeenIt = 900101 // Thing Seen: Seen It", // class caption prefix dropped
		"IP   string `json:\"ip,omitempty\"`",                    // ip_t resolves to string_t
		"Port int    `json:\"port,omitempty\"`",
	} {
		if !strings.Contains(strings.Join(strings.Fields(src), " "), strings.Join(strings.Fields(want), " ")) {
			t.Errorf("generated source lacks %q:\n%s", want, src)
		}
	}
	for _, unwanted := range []string{"Old ", "Cloud ", "type Device"} {
		if strings.Contains(src, unwanted) {
			t.Errorf("generated source has %q (deprecated, profile-only or not allowlisted)", unwanted)
		}
	}
	if withProfile := generate(t, Config{Classes: []string{"thing_seen"}, Objects: []string{"network_endpoint"}, Profiles: []string{"cloud"}}); !strings.Contains(withProfile, "Cloud ") {
		t.Error("profile cloud listed but its attribute was not generated")
	}
}

func TestGenerateErrors(t *testing.T) {
	for name, cfg := range map[string]Config{
		"unknown class":  {Classes: []string{"nope"}},
		"unknown object": {Classes: []string{"thing_seen"}, Objects: []string{"nope"}},
	} {
		if _, err := Generate([]byte(fixture), cfg, "ocsf"); err == nil {
			t.Errorf("%s: no error", name)
		}
	}
	// A required attribute whose object is not allowlisted is an error.
	req := strings.Replace(fixture, `"object_type": "network_endpoint", "requirement": "recommended"`, `"object_type": "network_endpoint", "requirement": "required"`, 1)
	if _, err := Generate([]byte(req), Config{Classes: []string{"thing_seen"}}, "ocsf"); err == nil || !strings.Contains(err.Error(), "required attribute peer") {
		t.Errorf("required object not allowlisted: %v", err)
	}
}

func TestNames(t *testing.T) {
	for in, want := range map[string]string{
		"activity_id": "ActivityID", "type_uid": "TypeUID", "http_request": "HTTPRequest", "is_mfa": "IsMFA", "src_endpoint": "SrcEndpoint",
	} {
		if got := goName(in); got != want {
			t.Errorf("goName(%q) = %q, want %q", in, got, want)
		}
	}
	if got := identifier("Service Ticket Request"); got != "ServiceTicketRequest" {
		t.Errorf("identifier = %q", got)
	}
	if got := identifier("3rd party"); got != "V3rdParty" {
		t.Errorf("identifier = %q", got)
	}
}
